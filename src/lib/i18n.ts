export const dictionaries: Record<Locale, Record<MessageKey, string>> = { ar, en };

export type TranslationKey = MessageKey;

export function translate(locale: Locale, key: TranslationKey, variables?: Record<string, string | number>): string {
  let value = dictionaries[locale][key] ?? dictionaries.ar[key] ?? key;
  if (variables) {
    for (const [name, replacement] of Object.entries(variables)) {
      value = value.replace(new RegExp(`\\{${name}\\}`, "g"), String(replacement));
    }
  }
  return value;
}

export function isLocale(value: string | undefined | null): value is Locale {
  return value === "ar" || value === "en";
}

export function normalizeLocale(value: string | undefined | null): Locale {
  return isLocale(value) ? value : "en";
}
